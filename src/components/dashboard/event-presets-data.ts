// HELPER TO LOOKUP EVENT PRESET BY TYPE
// ============================================================================
export function getPresetForEventType(type: string): EventPresetBundle {
  const normalized = (type || "").toLowerCase().trim();
  if (
    normalized.includes("communit") ||
    normalized.includes("festiv") ||
    normalized.includes("mela") ||
    normalized.includes("mahotsav") ||
    normalized.includes("society")
  ) {
    return communityFestivalPreset;
  }
  if (
    normalized.includes("birth") ||
    normalized.includes("bday") ||
    normalized.includes("jubilee") ||
    normalized.includes("kids party")
  ) {
    return birthdayPreset;
  }
  if (
    normalized.includes("anniv") ||
    normalized.includes("silver") ||
    normalized.includes("golden")
  ) {
    return anniversaryPreset;
  }
  if (
    normalized.includes("reunion") ||
    normalized.includes("get-together") ||
    normalized.includes("homecoming") ||
    normalized.includes("corporate")
  ) {
    return familyReunionPreset;
  }
  return royalWeddingPreset; // Defaults to Royal Wedding
}
